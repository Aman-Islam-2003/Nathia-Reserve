// Writes styles/font-fallbacks.css: size-adjusted fallback faces for every theme font, so text painted
// before the web font arrives already has the web font's width and line height (no layout shift on swap).
//
// Why not next/font's adjustFontFallback: it emits one fallback face with a single source,
// local(Times New Roman) or local(Arial). Linux (where PageSpeed Insights runs) and Android usually have
// neither, so that face doesn't exist there and text first renders in an unadjusted default font, then
// jumps when the web font loads (PSI measured CLS 0.193 on the real-estate demo).
//
// Each font gets two faces, tried in order:
//   "<Family> Fallback":         Times New Roman / Arial and their metric-compatible twins
//                                (Liberation Serif/Sans on Linux, Tinos/Arimo on ChromeOS), same overrides
//   "<Family> Fallback Android": Noto Serif / Roboto, with overrides computed for those fonts
// Metrics and the formula are next/font's (next/dist/server/capsize-font-metrics.json, font-utils.js).
//
// Run `npm run fonts` after adding or changing a theme font, and add the families to the font's
// `fallback` list in themes/fonts/<theme>.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const metrics = JSON.parse(readFileSync(require.resolve("next/dist/server/capsize-font-metrics.json"), "utf8"));

/** Theme fonts (themes/fonts/*.ts): CSS family name, metrics key, and serif / sans (default) / mono. */
const FONTS = [
  { family: "Cormorant Garamond", key: "cormorantGaramond", serif: true },
  { family: "Jost", key: "jost", serif: false },
  { family: "DM Sans", key: "dMSans", serif: false },
  { family: "Unbounded", key: "unbounded", serif: false },
  { family: "Instrument Sans", key: "instrumentSans", serif: false },
  { family: "IBM Plex Mono", key: "iBMPlexMono", mono: true },
];

const FALLBACKS = {
  serif: [
    { suffix: "Fallback", key: "timesNewRoman", sources: ["Times New Roman", "TimesNewRomanPSMT", "Liberation Serif", "LiberationSerif", "Tinos"] },
    { suffix: "Fallback Android", key: "notoSerif", sources: ["Noto Serif", "NotoSerif"] },
  ],
  // Courier New, Liberation Mono and Cousine share one set of metrics; Android has Noto Sans Mono / Droid Sans Mono.
  mono: [
    { suffix: "Fallback", key: "courierNew", sources: ["Courier New", "CourierNewPSMT", "Liberation Mono", "LiberationMono", "Cousine"] },
    { suffix: "Fallback Android", key: "notoSansMono", sources: ["Noto Sans Mono", "NotoSansMono", "Droid Sans Mono"] },
  ],
  sans: [
    { suffix: "Fallback", key: "arial", sources: ["Arial", "ArialMT", "Liberation Sans", "LiberationSans", "Arimo"] },
    { suffix: "Fallback Android", key: "roboto", sources: ["Roboto", "Roboto Regular", "Roboto-Regular"] },
  ],
};

const pct = (v) => `${parseFloat((Math.abs(v) * 100).toFixed(2))}%`;

/** next/font's calculateSizeAdjustValues, with a chosen fallback font. */
function overrides(main, fallback) {
  const a = metrics[main], b = metrics[fallback];
  if (!a || !b) throw new Error(`No metrics for ${!a ? main : fallback}`);
  const sizeAdjust = a.xWidthAvg / a.unitsPerEm / (b.xWidthAvg / b.unitsPerEm);
  const per = (v) => pct(v / (a.unitsPerEm * sizeAdjust));
  return { sizeAdjust: pct(sizeAdjust), ascent: per(a.ascent), descent: per(a.descent), lineGap: per(a.lineGap) };
}

const faces = FONTS.flatMap(({ family, key, serif, mono }) =>
  FALLBACKS[mono ? "mono" : serif ? "serif" : "sans"].map(({ suffix, key: fallbackKey, sources }) => {
    const o = overrides(key, fallbackKey);
    // Unquoted local() names are valid CSS (identifiers); the first one installed is used.
    return `@font-face {
  font-family: "${family} ${suffix}";
  src: ${sources.map((s) => `local(${s})`).join(", ")};
  ascent-override: ${o.ascent};
  descent-override: ${o.descent};
  line-gap-override: ${o.lineGap};
  size-adjust: ${o.sizeAdjust};
}`;
  }),
);

writeFileSync(
  new URL("../styles/font-fallbacks.css", import.meta.url),
  `/* Generated by scripts/font-fallbacks.mjs (npm run fonts). Do not edit by hand. */\n\n${faces.join("\n\n")}\n`,
);
console.log(`styles/font-fallbacks.css: ${faces.length} fallback faces`);
